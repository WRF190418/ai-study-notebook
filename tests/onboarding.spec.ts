import { expect, test, type Page } from "@playwright/test";
import sharp from "sharp";
import { createCourseWithStarterLesson, createNote } from "../lib/db";
import { guideSteps } from "../lib/onboarding";

async function register(page: Page, label: string) {
  expect((await page.request.post("/api/auth/register", { data: { name: "跟着学笔记本", email: `guide-${label}-${Date.now()}@example.com`, password: "12345678" } })).ok()).toBeTruthy();
  return (await page.request.get("/api/workspace")).json();
}

test("first-run guide teaches actual features, handles empty notes and can be reopened", async ({ page }, testInfo) => {
  await register(page, `empty-${testInfo.project.name}`);
  let aiCalls = 0;
  page.on("request", request => { if (request.url().includes("/api/ai/")) aiCalls++; });
  await page.goto("/");
  const guide = page.getByRole("dialog", { name: "新手指导", exact: true });
  await expect(guide).toBeVisible();
  await expect(guide.getByRole("navigation", { name: "新手指导目录" }).getByRole("button")).toHaveCount(10);
  await guide.getByRole("button", { name: /第 5 步/ }).click();
  await expect(guide).toContainText("当前没有含「第 N 页」标题");
  await guide.getByRole("button", { name: "先去了解如何准备笔记" }).click();
  await expect(guide).toBeHidden();
  const practice = page.getByRole("complementary", { name: "手把手操作指引" });
  await expect(practice).toContainText("补充与整理资料");
  await expect(page.locator(".organizer")).toBeVisible();
  await expect(page.getByLabel("整理要求", { exact: true })).toBeEmpty();
  await expect(page.getByLabel("AI 命令行", { exact: true })).toBeEmpty();
  await practice.getByRole("button", { name: "完整指引", exact: true }).click();
  await expect(guide).toContainText("当前默认做法是把文件发给 Codex");
  await expect(guide.locator('[aria-current="step"]')).toContainText("补充与整理资料");
  await page.screenshot({ path: `test-results/guide-organizer-${testInfo.project.name}.png` });
  await guide.getByRole("button", { name: "跳过", exact: true }).click();
  await expect(practice).toHaveCount(0);
  await expect(guide).toBeHidden();
  await expect.poll(async () => (await (await page.request.get("/api/workspace")).json()).user.onboardingCompletedAt).toBeTruthy();
  await page.reload();
  await expect(guide).toHaveCount(0);
  await page.getByRole("button", { name: "新手指导", exact: true }).click();
  await expect(guide).toBeVisible();
  await expect(guide.locator('[aria-current="step"]')).toContainText("主页与续读");
  await page.keyboard.press("Escape");
  await expect(guide).toBeHidden();
  expect(aiCalls).toBe(0);
});

test("guide jumps to real cross-term notes, source images, stars, focus, OCR and review without edits", async ({ page }, testInfo) => {
  test.setTimeout(180_000);
  if (testInfo.project.name === "desktop") await page.setViewportSize({ width: 1440, height: 900 });
  const initial = await register(page, `real-${testInfo.project.name}`);
  const { course, lesson } = await createCourseWithStarterLesson(initial.user.id, { title: "向导实操课程", code: "GUIDE", term: "2027年春季学期", description: "验证跨学期导航", lessonTitle: "亲手试一试", lessonSubtitle: "Real, not simulated" });
  const note = await createNote({ userId: initial.user.id, courseId: course.id, lessonId: lesson.id, title: "向导使用的真实笔记", sourceType: "text", sourceText: "操作向导测试", contentMarkdown: `# 向导使用的真实笔记\n\n### 第1页｜先建立框架\n\n${"学习需要把概念放回上下文。".repeat(150)}\n\n### 第2页｜原图与重点\n\n向导检索唯一词。图中的英文、数字和标点都可以选择复制。`, summary: "不自动修改内容", flashcards: [{ id: "guide-card", front: "学完要做什么？", back: "回看结构并自测。", difficulty: "easy" }], mindMap: [{ id: "guide-map", label: "理解", children: [{ id: "guide-child", label: "回顾" }] }] });
  const image = await sharp({ create: { width: 720, height: 260, channels: 3, background: "#dce9e2" } }).png().toBuffer();
  expect((await page.request.post(`/api/notes/${note.id}/images`, { multipart: { placement: "end", alt: "向导英文图片", image: { name: "guide-image.png", mimeType: "image/png", buffer: image } } })).ok()).toBeTruthy();
  const before = await (await page.request.get("/api/workspace")).json();
  const errors: string[] = [], aiRequests: string[] = [], ocrRequests: string[] = [];
  page.on("pageerror", error => errors.push(error.message));
  page.on("console", message => { if (message.type() === "error") errors.push(message.text()); });
  page.on("request", request => { if (request.url().includes("/api/ai/")) aiRequests.push(request.url()); if (request.url().includes("/api/ocr/")) ocrRequests.push(request.url()); });
  await page.goto("/");
  const guide = page.getByRole("dialog", { name: "新手指导", exact: true });
  const practice = page.getByRole("complementary", { name: "手把手操作指引" });
  await expect(guide).toBeVisible();
  async function launch(index: number) {
    if (!(await guide.isVisible())) await practice.getByRole("button", { name: "完整指引", exact: true }).click();
    await guide.getByRole("button", { name: new RegExp(`第 ${index + 1} 步`) }).click();
    await guide.getByRole("button", { name: guideSteps[index].action, exact: true }).click();
    await expect(guide).toBeHidden();
    await expect(practice).toBeVisible();
  }
  await launch(3);
  await expect(page.locator(".note-reader")).toContainText(note.title);
  await expect(page.getByLabel("选择学期", { exact: true })).toHaveValue(course.term);
  const original = page.getByRole("button", { name: "查看第2页原课件", exact: true });
  await expect(original).toBeInViewport();
  await expect(page.locator(".guide-target-ring")).toBeVisible();
  await practice.getByRole("button", { name: "收起操作指引" }).click();
  await original.click();
  await expect(page.getByRole("dialog", { name: "第2页原课件", exact: true })).toBeVisible();
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "展开操作指引" }).click();
  await launch(4);
  await expect(page.getByRole("button", { name: "加入加星列表：第1页", exact: true })).toBeInViewport();
  await expect(page.locator(".page-note-editor")).toHaveCount(0);
  await launch(6);
  await expect(page.locator(".sidebar-focus-button")).toBeInViewport();
  await page.locator(".sidebar-focus-button").click();
  await expect(page.locator(".app-shell")).toHaveClass(/focus-mode/);
  const toolbar = page.getByRole("toolbar", { name: "专注阅读工具栏" });
  await toolbar.hover();
  await page.getByRole("button", { name: "切换为深色阅读", exact: true }).click();
  await expect(page.locator(".app-shell")).toHaveClass(/focus-dark/);
  await practice.getByRole("button", { name: "完整指引", exact: true }).click();
  await page.keyboard.press("Escape");
  await expect(guide).toBeHidden();
  await expect(page.locator(".app-shell")).toHaveClass(/focus-mode/);
  // Reopen the library from the sidebar after leaving focus; this is now a completed guide.
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "新手指导", exact: true }).click();
  await launch(7);
  await expect(page.getByRole("button", { name: "识别并选择英文：向导英文图片", exact: true })).toBeInViewport();
  await expect(page.locator(".guide-target-ring")).toBeVisible();
  await launch(9);
  await expect(page.locator(".artifact-grid")).toContainText("学完要做什么？");
  await expect(page.locator(".artifact-grid")).toBeInViewport();
  await launch(5);
  await expect(page.getByLabel("搜索全部笔记")).toBeFocused();
  await page.getByLabel("搜索全部笔记").fill("向导检索唯一词");
  const results = page.getByRole("region", { name: "笔记搜索结果" });
  await expect(results).toContainText("第2页");
  await practice.getByRole("button", { name: "收起操作指引" }).click();
  await results.getByRole("button", { name: /第2页/ }).click();
  await expect(page.getByRole("heading", { name: /第2页.*原图与重点/ })).toBeInViewport();
  await page.getByRole("button", { name: "展开操作指引" }).click();
  await launch(1);
  await page.getByRole("dialog", { name: "空间主题", exact: true }).locator(".theme-card-poetic-realm").click();
  await expect(page.locator(".poem-home")).toBeVisible();
  await expect(practice).toBeVisible();
  const after = await (await page.request.get("/api/workspace")).json();
  expect(after.notes).toEqual(before.notes);
  expect(after.noteStars).toEqual(before.noteStars);
  expect(after.courses).toEqual(before.courses);
  expect(after.lessons).toEqual(before.lessons);
  expect(aiRequests).toEqual([]);
  expect(ocrRequests).toEqual([]);
  expect(errors).toEqual([]);
});
