import { expect, test } from "@playwright/test";
import { createNote, updateNote } from "../lib/db";
import { saveNoteImage } from "../lib/media";
import sharp from "sharp";

test("open book keeps its index, source images and annotation drafts through long reading", async ({ page }, info) => {
  test.skip(info.project.name !== "desktop");
  await page.setViewportSize({ width: 1600, height: 1000 });
  expect((await page.request.post("/api/auth/register", { data: { name: "随身本读者", email: `open-book-${Date.now()}@example.com`, password: "12345678" } })).ok()).toBeTruthy();
  await page.request.post("/api/onboarding");
  const initial = await (await page.request.get("/api/workspace")).json(), chapter = initial.lessons[0];
  const note = await createNote({ userId: initial.user.id, courseId: chapter.courseId, lessonId: chapter.id, title: "光与运动：随身学习条目", sourceType: "text", sourceText: "原创测试材料，非用户课件", summary: "从实验图像出发，理解条件、公式和结论之间的关系。", contentMarkdown: "", flashcards: [], mindMap: [] });
  const diagram = await sharp(Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="1000" height="420"><rect width="1000" height="420" fill="#fbfcff"/><text x="50" y="65" fill="#24364a" font-size="30" font-family="Arial">Light and motion / original test diagram</text><path d="M100 340H900M100 340V110M100 340L800 130" stroke="#396779" fill="none" stroke-width="3"/><text x="840" y="375" font-size="20">Time (s)</text><text x="130" y="130" font-size="20">Distance (m)</text><circle cx="450" cy="255" r="7" fill="#aa674a"/></svg>')).png().toBuffer();
  const asset = await saveNoteImage({ userId: initial.user.id, noteId: note.id, file: new File([new Uint8Array(diagram)], "reading-fixture.png", { type: "image/png" }), source: { slideNumber: 1, sourceFile: "原创验收图", width: 1000, height: 420 } });
  const paragraphs = "学习这一页时，先确认讨论对象及适用条件，再把实验观察与模型中的量对应起来。图中的横轴表示时间，纵轴表示距离，直线斜率对应速度；只有匀速运动时，才可用同一斜率描述整个区间。";
  const content = "## 概念框架\n\n观察 → 建模 → 核对条件 → 解释结果。\n\n" + Array.from({ length: 12 }, (_, i) => `### 第${i + 1}页｜${i ? `模型与证据 ${i + 1}` : "观察光与运动"}\n\n${paragraphs}\n\n${i === 0 ? `![原创验收图，第1页，距离随时间变化的坐标图](/api/media/${asset.id})\n\n**读图提示：** 从横轴时间和纵轴距离出发，沿直线看位置如何变化。` : paragraphs}\n\n速度 $v=\\frac{\\Delta x}{\\Delta t}$，其中位移单位为米，时间单位为秒。\n\n| 量 | 单位 |\n| --- | --- |\n| 位移 | m |\n| 时间 | s |\n`).join("\n\n") + `\n<!-- courseware-appendix -->\n\n### 原课件第1页\n\n![原创验收图，第1页，完整原页](/api/media/${asset.id})`;
  await updateNote(initial.user.id, note.id, { contentMarkdown: content });
  const other = await createNote({ userId: initial.user.id, courseId: chapter.courseId, lessonId: chapter.id, title: "同章的另一篇笔记", sourceType: "text", sourceText: "测试", summary: "确认同章切换。", contentMarkdown: "### 第1页｜另一篇的起点\n\n不同笔记保留各自的逐页目录。", flashcards: [], mindMap: [] });
  await page.request.put("/api/preferences", { data: { theme: "galactic-guide" } });
  const forbidden: string[] = [];
  page.on("request", r => { if (/\/api\/ai\//.test(r.url())) forbidden.push(r.url()); });
  await page.goto("/");
  await page.locator(".guide-course").first().click();
  await page.locator(".course-chapter").first().click();
  await page.locator(".notes-list .note-item").filter({ hasText: note.title }).click();
  const directory = page.getByRole("navigation", { name: "本篇逐页目录" });
  await expect(directory.getByRole("button")).toHaveCount(12);
  await page.getByRole("button", { name: "查看第1页原课件", exact: true }).click();
  const original = page.getByRole("dialog", { name: "第1页原课件", exact: true });
  await expect(original.locator("img")).toHaveJSProperty("naturalWidth", 1000);
  await original.getByRole("button", { name: "关闭原课件预览" }).click();
  const picture = page.locator(".note-reader .markdown img").first();
  const proportions = await picture.evaluate(el => { const a = el.getBoundingClientRect(); return a.width / a.height; });
  expect(proportions).toBeCloseTo(1000 / 420, 1);
  await page.locator('[data-scroll-region="notes"]').evaluate(el => { el.scrollTop = 0; });
  await page.screenshot({ path: "test-results/galactic-open-book-desktop.png", animations: "disabled" });
  await directory.getByRole("button", { name: /12.*模型与证据 12/ }).focus();
  await page.keyboard.press("Enter");
  await expect(page.getByRole("heading", { name: /第12页.*模型与证据 12/ })).toBeInViewport();
  await expect(directory).toBeInViewport();
  await expect(directory.locator('[aria-current="location"]')).toContainText("12");
  await page.screenshot({ path: "test-results/galactic-open-book-reading.png", animations: "disabled" });
  await directory.getByRole("button", { name: /03.*模型与证据 3/ }).click();
  await page.getByRole("button", { name: "加入加星列表：第3页", exact: true }).click();
  const editor = page.getByRole("dialog", { name: "第3页备注编辑器", exact: true });
  await editor.getByLabel("第3页备注内容", { exact: true }).fill("先核对坐标单位，再看斜率。");
  await page.locator(".sidebar-focus-button").click();
  await expect(editor.getByLabel("第3页备注内容", { exact: true })).toHaveValue("先核对坐标单位，再看斜率。");
  await page.locator(".focus-reader-toolbar").hover();
  await page.locator(".focus-theme-toggle").click();
  await expect(editor.getByLabel("第3页备注内容", { exact: true })).toHaveValue("先核对坐标单位，再看斜率。");
  const saved = page.waitForResponse(r => r.url().endsWith("/api/stars") && r.request().method() === "PUT");
  await editor.locator(".page-note-save").click();
  expect((await saved).ok()).toBeTruthy();
  await page.screenshot({ path: "test-results/galactic-open-book-dark.png", animations: "disabled" });
  await page.keyboard.press("Escape");
  await page.locator(".notes-list .note-item").filter({ hasText: other.title }).click();
  await expect(directory.getByRole("button")).toHaveCount(1);
  await expect(page.locator(".note-reader")).toContainText("另一篇的起点");
  expect(forbidden).toEqual([]);
  const after = await (await page.request.get("/api/workspace")).json();
  expect(after.notes.find((n: { id: string }) => n.id === note.id).contentMarkdown).toBe(content);
  expect(after.noteStars).toEqual(expect.arrayContaining([expect.objectContaining({ noteId: note.id, pageNumber: 3, note: "先核对坐标单位，再看斜率。" })]));
});
